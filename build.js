// Research Desk — packs src/ into the single self-contained file "Research Desk offline.html":
// stylesheets and scripts are inlined, fonts become data: URIs. No dependencies — Node.js is enough.
// Run with: node build.js  (start.bat does it on every start; server.js also serves a fresh build of src/).
'use strict';
const fs = require('fs');
const path = require('path');

const SRC_DIR = path.join(__dirname, 'src');
const OUT_FILE = path.join(__dirname, 'Research Desk offline.html');
const MIME = { '.woff2': 'font/woff2', '.woff': 'font/woff', '.ttf': 'font/ttf', '.png': 'image/png', '.jpg': 'image/jpeg', '.svg': 'image/svg+xml' };
const HEADER = '<!-- Generated by build.js from src/ — do not edit this file; edit src/ and run: node build.js -->\n';

const isLocal = ref => !/^([a-z][a-z0-9+.-]*:|\/\/|#)/i.test(ref);

function read(file) {
  return fs.readFileSync(file, 'utf8').replace(/^﻿/, '');
}

// url(...) references in CSS become data: URIs.
function inlineCss(file) {
  return read(file).replace(/url\((["']?)([^"')]+)\1\)/g, (all, quote, ref) => {
    if (!isLocal(ref)) return all;
    const target = path.resolve(path.dirname(file), ref);
    const mime = MIME[path.extname(target).toLowerCase()];
    if (!mime) throw new Error('Unknown asset type in ' + path.relative(__dirname, file) + ': ' + ref);
    return 'url("data:' + mime + ';base64,' + fs.readFileSync(target).toString('base64') + '")';
  });
}

// Inside an inline <script>, "</script" would end the element early and "<!--" changes how the parser reads it.
function inlineJs(file) {
  const js = read(file);
  if (js.includes('<!--')) throw new Error(path.relative(__dirname, file) + ' contains "<!--", which cannot be inlined safely.');
  return js.replace(/<\/(script)/gi, '<\\/$1');
}

function buildHtml() {
  const at = ref => path.resolve(SRC_DIR, ref);
  const html = read(path.join(SRC_DIR, 'index.html'))
    .replace(/<link rel="stylesheet" href="([^"]+)">/g, (all, href) =>
      isLocal(href) ? '<style>\n' + inlineCss(at(href)) + '</style>' : all)
    .replace(/<script([^>]*?) src="([^"]+)"([^>]*)><\/script>/g, (all, before, src, after) =>
      isLocal(src) ? '<script' + before + after + '>\n' + inlineJs(at(src)) + '</script>' : all);
  const unresolved = html.match(/<(script|link)\b[^>]*\b(src|href)="(?![a-z][a-z0-9+.-]*:|\/\/)[^"]*"/i);
  if (unresolved) throw new Error('Could not inline: ' + unresolved[0]);
  return html.replace(/^(<!DOCTYPE html>\n)?/i, (doctype) => doctype + HEADER);
}

function build() {
  const html = buildHtml();
  if (!fs.existsSync(OUT_FILE) || fs.readFileSync(OUT_FILE, 'utf8') !== html) fs.writeFileSync(OUT_FILE, html);
  return html;
}

if (require.main === module) {
  try {
    const html = build();
    console.log('Built ' + path.basename(OUT_FILE) + ' (' + Math.round(Buffer.byteLength(html) / 1024) + ' kB)');
  } catch (e) {
    console.error('Build failed: ' + e.message);
    process.exit(1);
  }
}

module.exports = { buildHtml, build, SRC_DIR, OUT_FILE };
